CREATE TABLE IF NOT EXISTS pet_progress (
  pet_id VARCHAR(36) NOT NULL PRIMARY KEY,
  level INT UNSIGNED NOT NULL DEFAULT 1,
  xp INT UNSIGNED NOT NULL DEFAULT 0,
  affection INT UNSIGNED NOT NULL DEFAULT 0,
  mood VARCHAR(12) NOT NULL DEFAULT 'neutral',
  interaction_count INT UNSIGNED NOT NULL DEFAULT 0,
  last_interaction_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_pet_progress_updated_at (updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
